import { test, expect } from '@playwright/test';

test('registration, refresh, ledger, inventory, confirmed voice, and logout', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/udhaar');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByRole('link', { name: 'Register', exact: true }).click();
  await page.getByLabel('Full Name', { exact: true }).fill('Browser Shopkeeper');
  await page.getByLabel('Shop Name', { exact: true }).fill('Browser Kirana');
  await page.getByLabel('Email Address', { exact: true }).fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('BrowserPassword42');
  await page.getByLabel('Confirm Password', { exact: true }).fill('BrowserPassword42');
  await page.getByRole('button', { name: 'Register & Open Dashboard' }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to DukaanSaathi AI' })).toBeVisible();
  await expect(page.getByText('Browser Shopkeeper · Browser Kirana')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Welcome to DukaanSaathi AI' })).toBeVisible();
  await page.getByRole('link', { name: /Udhaar Ledger/ }).click();
  await page.getByRole('button', { name: 'Add New Customer' }).click();
  await page.getByPlaceholder('E.g. Ramesh Kumar').fill('Mahesh');
  await page.getByRole('button', { name: 'Create Customer' }).click();
  await expect(page.getByRole('button', { name: 'Active Customers (1)', exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: 'Mahesh' })).toBeVisible();
  await page.reload();
  const row = page.getByRole('row').filter({ hasText: 'Mahesh' });
  await expect(row).toBeVisible();
  await row.getByTitle('Add Udhaar', { exact: true }).click();
  await page.getByPlaceholder('E.g. 40', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Add Udhaar', exact: true }).last().click();
  await expect(row).toContainText('100');
  await row.getByTitle('Record Repayment', { exact: true }).click();
  await page.getByPlaceholder('E.g. 40', { exact: true }).fill('40');
  await page.getByRole('button', { name: 'Save Repayment', exact: true }).click();
  await expect(row).toContainText('60');
  await row.getByRole('button', { name: 'Delete or Archive Customer' }).click();
  await page.getByRole('button', { name: 'Archive Customer', exact: true }).click();
  await page.getByRole('button', { name: /Archived Customers/ }).click();
  await expect(row).toBeVisible();
  await page.getByRole('button', { name: 'Voice Assistant', exact: true }).click();
  await page.getByRole('button', { name: 'Close assistant' }).click();
  await row.getByTitle('Restore Customer to Active Ledger', { exact: true }).click();
  await page.getByRole('button', { name: 'Active Customers (1)', exact: true }).click();
  await expect(row).toBeVisible();
  await page.getByRole('link', { name: /Inventory/ }).click();
  await page.getByRole('button', { name: 'Add New Product', exact: true }).click();
  await page.getByPlaceholder('E.g. Amul Taaza Milk, Tata Sugar, Red Label Tea').fill('Milk');
  // Product labels in the existing form are visual; scope inputs to its modal.
  const modal = page.locator('div.fixed.inset-0').filter({ hasText: 'Add New Product' });
  await modal.locator('input[type=number]').nth(0).fill('32');
  await modal.locator('input[type=number]').nth(1).fill('20');
  await modal.getByRole('button', { name: 'Add to Inventory', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Milk', exact: true })).toBeVisible();
  await expect(page.getByText('20 packets', { exact: true })).toBeVisible();
  await page.getByTitle('Reduce Stock', { exact: true }).click();
  await page.locator('div.fixed.inset-0 input[type=number]').fill('5');
  await page.getByRole('button', { name: 'Confirm Reduce Stock', exact: true }).click();
  await expect(page.getByText('15 packets', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
  const input = page.getByPlaceholder(/Ramesh ko 40 rupaye udhaar do/);
  await input.fill('Mahesh ko 10 rupaye udhaar do');
  await input.press('Enter');
  await expect(page.getByRole('button', { name: /Confirm & Save/ })).toBeVisible();
  await page.getByRole('button', { name: /Confirm & Save/ }).click();
  await expect(page.getByRole('button', { name: /Confirm & Save/ })).not.toBeVisible();
  await page.getByRole('link', { name: /Udhaar Ledger/ }).click();
  await expect(page.getByRole('row').filter({ hasText: 'Mahesh' })).toContainText('70');
  await page.getByRole('button', { name: 'Logout', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email Address', { exact: true }).fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('BrowserPassword42');
  await page.getByRole('button', { name: 'Log In', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to DukaanSaathi AI' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('login and registration fit a mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/login');
  await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Register', exact: true }).click();
  await expect(page.getByLabel('Confirm Password', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
